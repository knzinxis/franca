CREATE OR REPLACE FUNCTION public.log_recruitment_status_change()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    INSERT INTO public.recruitment_history (
      recruitment_id,
      old_status,
      new_status,
      changed_by
    )
    VALUES (NEW.id::text, NULL, NEW.status, auth.uid());
    RETURN NEW;
  END IF;

  IF TG_OP = 'DELETE' THEN
    DELETE FROM public.recruitment_history
    WHERE recruitment_id = OLD.id::text;
    RETURN OLD;
  END IF;

  IF OLD.status IS DISTINCT FROM NEW.status THEN
    INSERT INTO public.recruitment_history (
      recruitment_id,
      old_status,
      new_status,
      changed_by
    )
    VALUES (NEW.id::text, OLD.status, NEW.status, auth.uid());
  END IF;
  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.log_recruitment_status_change() FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS recruitment_status_history_insert ON public.recruitments;
CREATE TRIGGER recruitment_status_history_insert
  AFTER INSERT ON public.recruitments
  FOR EACH ROW
  EXECUTE FUNCTION public.log_recruitment_status_change();

DROP TRIGGER IF EXISTS recruitment_status_history_update ON public.recruitments;
CREATE TRIGGER recruitment_status_history_update
  AFTER UPDATE OF status ON public.recruitments
  FOR EACH ROW
  EXECUTE FUNCTION public.log_recruitment_status_change();

DROP TRIGGER IF EXISTS recruitment_status_history_delete ON public.recruitments;
CREATE TRIGGER recruitment_status_history_delete
  AFTER DELETE ON public.recruitments
  FOR EACH ROW
  EXECUTE FUNCTION public.log_recruitment_status_change();

INSERT INTO public.recruitment_history (
  recruitment_id,
  old_status,
  new_status
)
SELECT recruitments.id::text, NULL, recruitments.status
FROM public.recruitments
WHERE NOT EXISTS (
  SELECT 1
  FROM public.recruitment_history
  WHERE recruitment_history.recruitment_id = recruitments.id::text
);
