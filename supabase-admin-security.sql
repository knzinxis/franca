-- Execute in Supabase SQL Editor before using the protected admin panel.
-- Create an Auth user in Supabase, then add that user's UUID to admin_users.

ALTER TABLE public.recruitments
  ADD COLUMN IF NOT EXISTS admin_notes text NOT NULL DEFAULT '';

CREATE TABLE IF NOT EXISTS public.admin_users (
  user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.recruitment_history (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recruitment_id text NOT NULL,
  old_status text,
  new_status text,
  changed_at timestamptz NOT NULL DEFAULT now(),
  changed_by uuid REFERENCES auth.users(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS recruitment_history_candidate_date_idx
  ON public.recruitment_history (recruitment_id, changed_at DESC);

DO $$
DECLARE
  existing_policy record;
BEGIN
  FOR existing_policy IN
    SELECT schemaname, tablename, policyname
    FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename IN ('recruitments', 'admin_users', 'recruitment_history')
  LOOP
    EXECUTE format(
      'DROP POLICY %I ON %I.%I',
      existing_policy.policyname,
      existing_policy.schemaname,
      existing_policy.tablename
    );
  END LOOP;
END
$$;

ALTER TABLE public.recruitments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.admin_users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.recruitment_history ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.recruitments FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.admin_users FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.recruitment_history FROM PUBLIC, anon, authenticated;

GRANT INSERT (
