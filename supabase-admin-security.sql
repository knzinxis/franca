) ON TABLE public.recruitments TO anon;

GRANT SELECT, UPDATE, DELETE ON TABLE public.recruitments TO authenticated;
GRANT SELECT ON TABLE public.admin_users TO authenticated;
GRANT SELECT ON TABLE public.recruitment_history TO authenticated;

CREATE POLICY recruitment_public_submission
  ON public.recruitments
  FOR INSERT
  TO anon
  WITH CHECK (status = 'Pendente');

